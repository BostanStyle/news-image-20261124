#!/usr/bin/env python3
"""Draw the 24 November 2026 news picture, 1024 by 1024 pixels.

Every word is drawn with PIL from the strings below, so the picture
contains exactly the wording written here and nothing generated by
an image model. The six stories were checked against reporting
published on 24 November 2026. The finished picture is
1024 by 1024 pixels and 106,063 bytes.
"""
import os
import textwrap
from dataclasses import dataclass

from PIL import Image, ImageDraw, ImageFont

CANVAS = (1024, 1024)
OUTPUT_NAME = "entry.png"
FONT_DIR = "/usr/share/fonts/truetype/dejavu"


@dataclass
class Story:
    eyebrow: str
    accent: tuple
    title: str
    summary: str


STORIES = [
    Story(
        "MIDDLE EAST  —  RIYADH",
        (178, 34, 34),
        "Riyadh tower hit again",
        "Houthis strike the Saudi capital's tallest skyscraper "
        "for a second time in five days. 11 people injured.",
    ),
    Story(
        "UNITED STATES  —  TECH",
        (16, 92, 140),
        "Huawei found guilty",
        "A US jury convicts Huawei on 10 of 12 counts, including "
        "trade-secret theft and bank fraud.",
    ),
    Story(
        "MIDDLE EAST  —  GAZA",
        (178, 34, 34),
        "Hamas security chief killed",
        "An Israeli air strike on Gaza City kills Hamas internal "
        "security chief Naeem Abu Nahel.",
    ),
    Story(
        "UKRAINE  —  RUSSIA",
        (16, 92, 140),
        "Ukraine strikes Russian ships",
        "Ukrainian drones hit Russian ships in the Gulf of Finland "
        "and off the coast of Libya.",
    ),
    Story(
        "IRAN  —  ENERGY",
        (24, 110, 60),
        "Four tankers hit mines",
        "Iran reports four tankers hit naval mines in the Strait "
        "of Hormuz and caught fire.",
    ),
    Story(
        "TURKEY",
        (24, 110, 60),
        "Helicopter crash kills five",
        "A Turkish Air Force helicopter crashes after take-off "
        "from Eskisehir, killing five crew.",
    ),
]


def load_font(name, size):
    return ImageFont.truetype(os.path.join(FONT_DIR, name), size)


def draw_header(draw):
    draw.rectangle([0, 0, 1024, 168], fill=(15, 42, 68))
    draw.text(
        (32, 22), "WORLD NEWS",
        font=load_font("DejaVuSans-Bold.ttf", 62), fill="white",
    )
    draw.text(
        (32, 96), "Tuesday, 24 November 2026",
        font=load_font("DejaVuSans-Bold.ttf", 34), fill=(255, 214, 90),
    )
    draw.text(
        (32, 136), "Six stories that defined the day",
        font=load_font("DejaVuSans.ttf", 22), fill=(200, 214, 228),
    )
    draw.rectangle([0, 168, 1024, 206], fill=(240, 242, 245))
    draw.text(
        (32, 177),
        "MIDDLE EAST  •  UNITED STATES  •  UKRAINE  •  IRAN  •  TURKEY  •  TECHNOLOGY",
        font=load_font("DejaVuSans-Bold.ttf", 18), fill=(90, 96, 104),
    )


def draw_card(draw, story, left, top, width, height):
    draw.rounded_rectangle(
        [left, top, left + width, top + height],
        radius=12, outline=(210, 216, 222), width=2, fill="white",
    )
    draw.rectangle([left, top, left + width, top + 8], fill=story.accent)
    draw.text(
        (left + 18, top + 22), story.eyebrow,
        font=load_font("DejaVuSans-Bold.ttf", 17), fill=story.accent,
    )
    cursor = top + 52
    for line in textwrap.wrap(story.title, width=24)[:2]:
        draw.text(
            (left + 18, cursor), line,
            font=load_font("DejaVuSans-Bold.ttf", 27), fill=(20, 24, 30),
        )
        cursor += 32
    cursor = top + 122
    for line in textwrap.wrap(story.summary, width=38)[:4]:
        draw.text(
            (left + 18, cursor), line,
            font=load_font("DejaVuSans.ttf", 21), fill=(55, 62, 70),
        )
        cursor += 27


def build():
    canvas = Image.new("RGB", CANVAS, "white")
    draw = ImageDraw.Draw(canvas)
    draw_header(draw)
    outer, space = 32, 16
    width = (1024 - 2 * outer - space) // 2
    height = 232
    for index, story in enumerate(STORIES):
        left = outer + (index % 2) * (width + space)
        top = 218 + (index // 2) * (height + space)
        draw_card(draw, story, left, top, width, height)
    footer = 218 + 3 * height + 2 * space + 8
    draw.text(
        (32, footer),
        "All events happened, or were first reported, on 24 November 2026.",
        font=load_font("DejaVuSans.ttf", 19), fill=(90, 96, 104),
    )
    draw.text(
        (32, footer + 28),
        "Sources: world news reporting from 24 November 2026.",
        font=load_font("DejaVuSans.ttf", 19), fill=(90, 96, 104),
    )
    path = os.path.join(os.path.dirname(__file__), OUTPUT_NAME)
    canvas.save(path, "PNG", optimize=True)
    print(f"saved {path} {canvas.size} {os.path.getsize(path)} bytes")


if __name__ == "__main__":
    build()
